/// The old chat stack's audit table the importer reads (database `jarvis`).
pub const JARVIS_SCHEMA: &str =
    "create table ops_events (id bigserial primary key, at timestamptz not null default now(),
    kind text not null, ok boolean, ms integer, sandbox_id uuid, conversation_id uuid, host text, detail jsonb)";

/// The world of one test.
pub struct World {
    pub imp: Importer,
    pub jfs: TempDir,
    pub service: Option<Service>,
    pub magpie_db: TestDb,
    pub cloudcli_db: TestDb,
    pub jarvis_db: TestDb,
}

impl World {
    pub async fn new(test: &str) -> Self {
        let _ = tracing::subscriber::set_global_default(
            tracing_subscriber::fmt()
                .with_test_writer()
                .with_max_level(tracing::Level::INFO)
                .finish(),
        );
        let magpie_db = fresh_db(&format!("mi_{test}")).await;
        let cloudcli_db = fresh_db(&format!("cc_{test}")).await;
        let jarvis_db = fresh_db(&format!("jv_{test}")).await;
        let bucket = bucket(&magpie_db.name).await;
        let readiness = Readiness::detached();
        let drain = Drain::new(readiness.clone());
        let cfg = Config {
            database_url: magpie_db.url.clone(),
            callers: aviary_core::auth::Callers::new(Vec::<(aviary_core::auth::Caller, Vec<String>)>::new()).unwrap(),
            hermit_url: "http://127.0.0.1:1".to_owned(),
            hermit_token: String::new(),
            pod: format!("magpie-import-test-{}", Uuid::new_v4().simple()),
            bucket,
            import_url: "http://127.0.0.1:1".to_owned(),
            import_token: String::new(),
            legacy_metrics: magpie::legacy::Metrics::default(),
        };
        let service = Service::start_library(cfg, &readiness, drain.draining()).await.unwrap();
        let cloudcli = aviary_pg::connect(&cloudcli_db.url, "magpie-import-test", 4, Duration::from_secs(30)).unwrap();
        let jarvis = aviary_pg::connect(&jarvis_db.url, "magpie-import-test", 2, Duration::from_secs(30)).unwrap();
        jarvis.get().await.unwrap().batch_execute(JARVIS_SCHEMA).await.unwrap();
        let jfs = TempDir(std::env::temp_dir().join(format!("magpie-import-{test}-{}", Uuid::new_v4().simple())));
        // a mounted volume has people in `users/` (the importer refuses a mount point that looks empty)
        std::fs::create_dir_all(jfs.0.join("users").join("u-mounted")).unwrap();
        Self {
            imp: Importer {
                magpie: Arc::clone(&service.app),
                cloudcli_schedules: cloudcli.clone(),
                cloudcli,
                jarvis,
                jfs: jfs.0.clone(),
                juicefs: None,
                lock: None,
                sent_quiet: Duration::ZERO,
                pause_in_fence: Duration::ZERO,
                owner: None,
            },
            jfs,
            service: Some(service),
            magpie_db,
            cloudcli_db,
            jarvis_db,
        }
    }

    pub fn magpie(&self) -> &aviary_pg::Pool {
        &self.imp.magpie.pool
    }

    /// Adds a person's schema; its key.
    pub async fn person(&self, email: &str) -> String {
        let key = aviary_core::log::person_key(email);
        let c = self.imp.cloudcli.get().await.unwrap();
        c.batch_execute(&format!(
            "create schema cc_{key}; set search_path = cc_{key}; {CLOUDCLI_SCHEMA}"
        ))
        .await
        .unwrap();
        c.execute(&format!("insert into cc_{key}.users (username) values ($1)"), &[&email])
            .await
            .unwrap();
        c.batch_execute("set search_path = public").await.unwrap();
        key
    }

    /// Runs a statement in `jarvis`.
    pub async fn jarvis(&self, sql: &str) {
        self.imp.jarvis.get().await.unwrap().batch_execute(sql).await.unwrap();
    }

    /// A share's folder (`users/<key>/shares/<id>`) with its frozen transcript, and its `cc_shared.shares` row.
    pub async fn share(&self, id: &str, owner: &str, conversation: Uuid, transcript: &[u8], revoked: bool) {
        let key = aviary_core::log::person_key(owner);
        let dir = self.jfs.0.join("users").join(&key).join("shares").join(id);
        std::fs::create_dir_all(dir.join("ws")).unwrap();
        std::fs::write(dir.join("transcript.jsonl"), transcript).unwrap();
        let c = self.imp.cloudcli.get().await.unwrap();
        c.batch_execute(
            "do $$ begin if to_regclass('cc_shared.shares') is null then
             create schema cc_shared; create table cc_shared.shares (id text primary key, owner text not null,
             owner_name text not null, session_id text not null, title text not null, dir text not null,
             files jsonb not null default '[]', created_at timestamptz not null default now(),
             revoked_at timestamptz); end if; end $$",
        )
        .await
        .unwrap();
        let revoked_at = revoked.then(|| "2026-10-28T04:52:12Z".to_owned());
        c.execute(
            "insert into cc_shared.shares (id, owner, owner_name, session_id, title, dir, created_at, revoked_at)
             values ($1, $2, split_part($2, '@', 1), $3, 'Shared', $4, '2026-10-28T03:04:32Z', $5::text::timestamptz)",
            &[
                &id,
                &owner,
                &conversation.to_string(),
                &format!("/jfs/users/{key}/shares/{id}"),
                &revoked_at,
            ],
        )
        .await
        .unwrap();
    }

    /// Revokes a share in `cloudcli`.
    pub async fn revoke_share(&self, id: &str) {
        self.imp
            .cloudcli
            .get()
            .await
            .unwrap()
            .execute("update cc_shared.shares set revoked_at = now() where id = $1", &[&id])
            .await
            .unwrap();
    }

    /// Runs a statement in `cloudcli`.
    pub async fn cloudcli(&self, sql: &str) {
        self.imp.cloudcli.get().await.unwrap().batch_execute(sql).await.unwrap();
    }

    /// The person's `claude/` folder.
    pub fn claude(&self, key: &str) -> PathBuf {
        magpie_import::tree::claude_dir(&self.jfs.0, key)
    }

    /// Writes a source file (folders made).
    pub fn put(&self, key: &str, rel: &str, bytes: &[u8]) -> PathBuf {
        let p = self.claude(key).join(rel);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(&p, bytes).unwrap();
        p
    }

    /// Appends to a source file.
    pub fn append(&self, key: &str, rel: &str, bytes: &[u8]) {
        use std::io::Write as _;
        let p = self.claude(key).join(rel);
        let mut f = std::fs::OpenOptions::new().append(true).open(p).unwrap();
        f.write_all(bytes).unwrap();
    }

    /// Replaces a file the way a compaction does: a temporary file renamed over it (a new inode).
    pub fn rename_over(&self, key: &str, rel: &str, bytes: &[u8]) {
        let p = self.claude(key).join(rel);
        let tmp = p.with_extension("tmp-rewrite");
        std::fs::write(&tmp, bytes).unwrap();
        std::fs::rename(&tmp, &p).unwrap();
    }

    pub fn workspace_upload(&self, conversation: Uuid, name: &str, bytes: &[u8]) {
        let d = self.jfs.0.join("ws").join(conversation.to_string()).join("uploads");
        std::fs::create_dir_all(&d).unwrap();
        std::fs::write(d.join(name), bytes).unwrap();
    }

    /// The event kinds of a conversation, in seq order.
    pub async fn kinds(&self, id: Uuid) -> Vec<String> {
        self.magpie()
            .get()
            .await
            .unwrap()
            .query(
                "select kind from events where conversation_id = $1 order by seq",
                &[&id],
            )
            .await
            .unwrap()
            .iter()
            .map(|r| r.get(0))
            .collect()
    }

    /// One column of a conversation, as JSON.
    pub async fn conv(&self, id: Uuid) -> serde_json::Value {
        self.magpie()
            .get()
            .await
            .unwrap()
            .query_one(
                "select jsonb_build_object('migrating', migrating, 'title', title, 'nameSource', name_source,
                        'deleted', deleted_at is not null, 'created', extract(epoch from created_at)::bigint,
                        'origin', origin, 'main', main_transcript, 'psid', provider_session_id, 'model', model)
                 from conversations where id = $1",
                &[&id],
            )
            .await
            .unwrap()
            .get(0)
    }

    /// Every cc file of a conversation and its version.
    pub async fn versions(&self, id: Uuid) -> Vec<(String, i64)> {
        self.magpie()
            .get()
            .await
            .unwrap()
            .query(
                "select path, version from cc_files where scope = $1 and kind <> 'dir' order by path",
                &[&id],
            )
            .await
            .unwrap()
            .iter()
            .map(|r| (r.get(0), r.get(1)))
            .collect()
    }
}

/// A Claude Code transcript line.
pub fn line(v: &serde_json::Value) -> Vec<u8> {
    let mut b = serde_json::to_vec(v).unwrap();
    b.push(b'\n');
    b
}

pub fn user(uuid: &str, ts: &str, text: &str) -> Vec<u8> {
    line(&serde_json::json!({
        "type": "user", "uuid": uuid, "timestamp": ts, "sessionId": "s",
        "message": {"role": "user", "content": text}
    }))
}

pub fn assistant(uuid: &str, ts: &str, text: &str) -> Vec<u8> {
    line(&serde_json::json!({
        "type": "assistant", "uuid": uuid, "timestamp": ts, "sessionId": "s",
        "message": {"id": format!("msg_{uuid}"), "role": "assistant", "model": "claude-test",
                    "content": [{"type": "text", "text": text}],
                    "usage": {"input_tokens": 10, "output_tokens": 5}}
    }))
}

/// A user line carrying an image (base64), the way Claude Code stores a pasted image.
pub fn user_image(uuid: &str, ts: &str, png: &[u8]) -> Vec<u8> {
    use base64::Engine as _;
    let data = base64::engine::general_purpose::STANDARD.encode(png);
    line(&serde_json::json!({
        "type": "user", "uuid": uuid, "timestamp": ts,
        "message": {"role": "user", "content": [
            {"type": "image", "source": {"type": "base64", "media_type": "image/png", "data": data}},
            {"type": "text", "text": "what is this"}
        ]}
    }))
}

pub fn path_of(p: &Path) -> String {
    p.to_string_lossy().into_owned()
}
