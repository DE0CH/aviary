pub fn admin_url() -> String {
    aviary_core::env::test_only("AVIARY_TEST_DATABASE_URL")
        .unwrap_or_else(|| panic!("AVIARY_TEST_DATABASE_URL is not set (ci.yml's test job sets it)"))
}

fn with_db(url: &str, db: &str) -> String {
    let (before, query) = url.split_once('?').map_or((url, None), |(b, q)| (b, Some(q)));
    let slash = before.rfind('/').expect("url has a database path");
    let mut out = format!("{}/{db}", &before[..slash]);
    if let Some(q) = query {
        out.push('?');
        out.push_str(q);
    }
    out
}

fn admin() -> aviary_pg::Pool {
    aviary_pg::connect(&admin_url(), "magpie-import-test-admin", 1, Duration::from_secs(15)).unwrap()
}

/// A test's own database, dropped with the guard.
pub struct TestDb {
    pub url: String,
    name: String,
}

impl Drop for TestDb {
    fn drop(&mut self) {
        let name = self.name.clone();
        let _ = std::thread::spawn(move || {
            let rt = tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()
                .unwrap();
            rt.block_on(async {
                admin()
                    .get()
                    .await?
                    .batch_execute(&format!("drop database if exists {name} with (force)"))
                    .await
            })
        })
        .join();
    }
}

pub async fn fresh_db(prefix: &str) -> TestDb {
    let name = format!("{prefix}_{}", Uuid::new_v4().simple());
    admin()
        .get()
        .await
        .unwrap()
        .batch_execute(&format!("create database {name}"))
        .await
        .unwrap();
    TestDb {
        url: with_db(&admin_url(), &name),
        name,
    }
}

pub async fn bucket(name: &str) -> BucketConfig {
    let env = |n: &str| aviary_core::env::test_only(n).unwrap_or_else(|| panic!("{n} is not set"));
    let cfg = BucketConfig {
        endpoint: env("AVIARY_TEST_S3_ENDPOINT"),
        region: env("AVIARY_TEST_S3_REGION"),
        bucket: name.replace('_', "-").chars().take(63).collect(),
        access_key_id: env("AVIARY_TEST_S3_ACCESS_KEY_ID"),
        secret_access_key: env("AVIARY_TEST_S3_SECRET_ACCESS_KEY"),
    };
    let b = magpie::blobs::store::Bucket::new(&cfg);
    if b.list("", None).await.is_err() && b.create().await.is_err() {
        b.list("", None).await.unwrap();
    }
    cfg
}

/// A temporary folder, removed with the guard.
pub struct TempDir(pub PathBuf);

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

