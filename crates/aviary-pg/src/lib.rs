//! Postgres for aviary services (platform 3.9, 4.3, 11): the connection pool, embedded migrations under an advisory
//! lock, the leader lock, the LISTEN helper, and transactions that cannot call out to the network.
//!
//! - [`connect`] builds a [`Pool`]: TLS required without certificate verification (`sslmode=require`), TCP
//!   keepalives 60/10/6, the service's `application_name`, and per-connection `statement_timeout` and
//!   `idle_in_transaction_session_timeout`; [`connect_read_only`] the same with `default_transaction_read_only = on`
//!   (a database the process must only read).
//! - [`migrate`] applies [`Migration`]s (embedded with [`migrations!`]) in order, once, under a session advisory
//!   lock, recorded in `_migrations` with their sha256; a recorded migration whose sha256 differs is a start failure.
//!   Each waits at most 5 s for a table lock and is retried with backoff, so an `alter table` never stalls the
//!   running replicas' queries behind it.
//! - [`Leader`] holds `pg_try_advisory_lock(key)` for one or more keys on one dedicated connection, says whether this
//!   process leads each, and [`Leader::confirm`]s it with `select 1` before every pass.
//! - [`Listener`] holds one dedicated LISTEN connection, reconnects with backoff, and wakes every [`Waiter`] after a
//!   reconnect so nothing missed in the gap is lost.
//! - [`tx!`] runs a closure in one transaction. **No transaction is held across a network call**: inside the closure
//!   a network call (`reqwest`, a contract crate's typed client, the Kubernetes API, an AWS SDK operation) is a
//!   clippy error in CI's second lint pass (configuration generated by `aviary_source_rules::tx_rule`), and the
//!   other ways into a transaction are refused ([`Conn`] refuses `begin`/`commit`; `clippy.toml` disallows the drivers'
//!   `transaction()`). A `tx!` whose closure ignored a statement error answers [`Error::RolledBack`], never a commit
//!   that did not happen.
//! - [`Pool::get`] gives a [`Conn`] for statements outside a transaction.
//! - While the database is away for a moment (a planned switchover), connections are waited for and cut statements
//!   and transactions run again ([`retry`]).

