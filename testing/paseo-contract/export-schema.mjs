#!/usr/bin/env node
// Exports JSON Schema of the Paseo message unions of one client build (pigeon spec 18.1), for pigeon's Rust tests:
// they validate every serde type's fixtures against it.
//
//   node export-schema.mjs [--commit SHA] [--check]
//
// Default commit: the newest client (the last line of clients.txt). Writes schema/<commit>.json with the outbound
// union (`WSOutboundMessageSchema`, what pigeon sends) and the inbound union (`WSInboundMessageSchema`, what pigeon
// reads), both as the schema's input side (what the parser accepts), and removes the previous newest client's file.
// `--check` writes nothing and exits 1 when the committed file differs from a fresh export, or when an older client's
// export is still committed.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

import { harnessRoot, protocolForCommit, readClients } from "./lib/protocol.mjs";

const args = process.argv.slice(2);
let commit = null;
let check = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--commit") commit = args[++i];
  else if (args[i] === "--check") check = true;
  else {
    console.error("usage: node export-schema.mjs [--commit SHA] [--check]");
    process.exit(2);
  }
}

async function exportSchema(sha) {
  const protocol = await protocolForCommit(sha);
  const { z } = protocol; // the zod instance the schemas were built with
  const options = { target: "draft-2020-12", io: "input", unrepresentable: "any", cycles: "ref", reused: "inline" };
  const document = {
    $comment:
      "Generated by testing/paseo-contract/export-schema.mjs from DE0CH/claudecodeui paseo/packages/protocol (zod's toJSONSchema, input side). Do not edit.",
    commit: sha,
    protocolTree: protocol.tree,
    outbound: z.toJSONSchema(protocol.messages.WSOutboundMessageSchema, options),
    inbound: z.toJSONSchema(protocol.messages.WSInboundMessageSchema, options),
  };
  return `${JSON.stringify(document, null, 1)}\n`;
}

try {
  const clients = readClients();
  const sha = commit ?? clients.at(-1).sha;
  const dir = path.join(harnessRoot, "schema");
  const file = path.join(dir, `${sha}.json`);
  const text = await exportSchema(sha);
  if (check) {
    let failed = false;
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
      console.error(`schema/${sha}.json is missing or stale: run node export-schema.mjs`);
      failed = true;
    }
    const stale = readdirSync(dir).filter((name) => name.endsWith(".json") && name !== `${sha}.json`);
    if (!commit && stale.length) {
      console.error(`only the newest client's schema is kept; remove ${stale.map((n) => `schema/${n}`).join(", ")}`);
      failed = true;
    }
    if (!failed) console.log(`schema/${sha}.json is current`);
    process.exit(failed ? 1 : 0);
  }
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, text);
  console.log(`wrote schema/${sha}.json (${text.length} bytes)`);
  if (!commit) {
    // only the newest client's schema is kept (pigeon's Rust types follow the newest client)
    for (const name of readdirSync(dir)) {
      if (name.endsWith(".json") && name !== `${sha}.json`) {
        rmSync(path.join(dir, name));
        console.log(`removed schema/${name}`);
      }
    }
  }
} catch (error) {
  console.error(`export-schema: ${error.stack ?? error}`);
  process.exit(2);
}
